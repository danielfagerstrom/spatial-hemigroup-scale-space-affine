#!/usr/bin/env python3
r"""The index of the complete proofs of the affine paper's sketched statements.

Appendix I lists the statements that the paper proves by a sketch only, and says that the LaTeX
sources deposited with the paper hold their complete proofs, under an index from statement numbers
to places. This script writes that index, records/affine/INDEX-complete-proofs.md, from three
things the repository already holds: the list in paper/appendix-verification.tex, the numbers in
paper/main.aux, and the blueprint's sources.

    python records/affine/gen-complete-proofs-index.py           # write the index
    python records/affine/gen-complete-proofs-index.py --check   # exit 1 if it would differ

Build the paper first: the numbers come from its .aux file. Refuses a statement whose label has no
blueprint node, whose node has no proof, or whose file is not among the chapters the export carries.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PARTS = ROOT / "blueprint" / "src" / "parts"
OUT = ROOT / "records" / "affine" / "INDEX-complete-proofs.md"
EXPORTED = ("02-", "04-", "05-")  # the chapters of the module `affine` in linkage.toml


def strip_comment(line):
    return re.sub(r"(?<!\\)%.*$", "", line)


def sketched_labels():
    text = (ROOT / "paper" / "appendix-verification.tex").read_text(encoding="utf-8")
    text = "\n".join(strip_comment(ln) for ln in text.splitlines())
    m = re.search(r"Twenty statements\s+have a sketch only:(.*?)Their complete proofs", text, re.S)
    if not m:
        sys.exit("the list of sketched statements is not in appendix-verification.tex")
    found = re.findall(r"\\ref\{([^}]+)\}(\(\d\)--\(\d\))?", m.group(1))
    if len(found) != 20:
        sys.exit(f"the list names {len(found)} statements, and the text says twenty")
    return found


def numbers():
    aux = (ROOT / "paper" / "main.aux").read_text(encoding="utf-8", errors="replace")
    return {m.group(1): m.group(2) for m in re.finditer(r"\\newlabel\{([^}]+)\}\{\{([^}]*)\}", aux)}


def locate(label):
    for part in sorted(PARTS.glob("*.tex")):
        lines = part.read_text(encoding="utf-8").splitlines()
        for i, ln in enumerate(lines):
            if f"\\label{{{label}}}" not in strip_comment(ln):
                continue
            # The proof that follows the node, before any further statement.
            for j in range(i + 1, len(lines)):
                code = strip_comment(lines[j])
                if "\\begin{proof}" in code:
                    end = next((k for k in range(j, len(lines))
                                if "\\end{proof}" in strip_comment(lines[k])), None)
                    if end is None:
                        sys.exit(f"{label}: an unclosed proof in {part.name}")
                    return part.name, j + 1, end + 1
                if re.search(r"\\begin\{(theorem|proposition|lemma|corollary|definition)\}", code):
                    break
            sys.exit(f"{label}: no proof follows the node in {part.name}")
    sys.exit(f"{label}: no blueprint node")


def number_key(number):
    head, _, tail = number.partition(".")
    return (head.isalpha(), head, int(tail) if tail.isdigit() else 0)


def render():
    nums = numbers()
    rows = []
    for label, clauses in sketched_labels():
        if label not in nums:
            sys.exit(f"{label}: not in paper/main.aux; build the paper first")
        name, start, end = locate(label)
        if not name.startswith(EXPORTED):
            sys.exit(f"{label}: its proof is in {name}, which the export does not carry")
        rows.append((nums[label], clauses.replace("--", "–"), label, name, start, end))
    rows.sort(key=lambda r: number_key(r[0]))
    out = [
        "# The complete proofs of the sketched statements",
        "",
        "Appendix I of the paper lists twenty statements whose proofs it gives as sketches. Their complete proofs",
        "are in the LaTeX sources deposited with the paper, the blueprint's chapters in `blueprint/src/parts/`, at",
        "the places below. A proof is the `proof` environment that follows the statement's `\\label` in the named file,",
        "at the lines given. Each of these statements is machine-checked like every other: the declarations are named in",
        "the `\\lean` tag of the same node.",
        "",
        "A proof may name a label that these chapters do not define, such as `prop:isotropic-polar-reading`. Such a label is in",
        "chapter 3 of the blueprint, the isotropic paper's, which is deposited with its release `iso-v0.1`.",
        "",
        "Generated by `records/affine/gen-complete-proofs-index.py` from the paper's list, its numbers and the blueprint.",
        "",
        "| Statement | Label | File | Lines of the proof |",
        "|---|---|---|---|",
    ]
    for number, clauses, label, name, start, end in rows:
        out.append(f"| {number}{clauses} | `{label}` | `blueprint/src/parts/{name}` | {start}–{end} |")
    return "\n".join(out) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        have = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if have != text:
            sys.exit(f"{OUT.relative_to(ROOT).as_posix()} is stale: run this script")
        print("the index holds")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {text.count(" | `blueprint/")} statements")


if __name__ == "__main__":
    main()
